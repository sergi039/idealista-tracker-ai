"""Explicit shortlist only. Dry-run creates a plan; --apply consumes it.

Free Catastro calls, no scoring or paid enrichment. No --all/default cohort.
Run tools/backfill_status.sh before any real run; announce IDs and zero cost.
"""

from __future__ import annotations

import argparse
from contextlib import nullcontext
import json
import logging
from pathlib import Path

from app import create_app, db
from models import Property
from services.neighbours_service import NeighboursService, subject
from utils.inflight import inflight

logger = logging.getLogger(__name__)
MAX_SHORTLIST = 20


def parse_ids(raw):
    try:
        ids = sorted({int(i.strip()) for i in raw.split(",")})
    except ValueError as exc:
        raise argparse.ArgumentTypeError(
            "--ids must be comma-separated positive integers"
        ) from exc
    if not ids or min(ids) <= 0 or len(ids) > MAX_SHORTLIST:
        raise argparse.ArgumentTypeError("--ids must name 1 to 20 shortlist rows")
    return ids


def plan_for(properties):
    return {
        "schema": 1,
        "rows": [
            {
                "id": p.id,
                "subject": subject(p),
                "previous": (p.enrichment or {}).get("neighbours"),
            }
            for p in properties
        ],
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ids", required=True, type=parse_ids)
    parser.add_argument(
        "--plan",
        type=Path,
        help="Dry-run plan / previous-block snapshot. Required with --apply.",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--dry-run", action="store_true", help="Default. No API calls or DB writes."
    )
    mode.add_argument(
        "--apply",
        action="store_true",
        help="Apply exactly the unchanged rows in a prior dry-run plan.",
    )
    args = parser.parse_args(argv)
    if args.apply and (not args.plan or not args.plan.is_file()):
        parser.error("--apply requires an existing --plan from a dry-run")
    app = create_app()
    with app.app_context():
        properties = (
            Property.query.filter(Property.id.in_(args.ids)).order_by(Property.id).all()
        )
        if [p.id for p in properties] != args.ids:
            parser.error(
                "some requested IDs do not exist; refusing a partial shortlist"
            )
        plan = plan_for(properties)
        if not args.apply:
            rendered = json.dumps(plan, indent=2, sort_keys=True)
            if args.plan:
                # Never overwrite the rollback snapshot from an earlier run.
                with args.plan.open("x") as output:
                    output.write(rendered + "\n")
            print(rendered)
            return
        if json.loads(args.plan.read_text()) != plan:
            parser.error(
                "plan no longer matches the requested IDs, subjects or previous blocks; dry-run again"
            )
        # Read-only query transaction ends before the writer's clean-session
        # contract. Only this dedicated service is called, never enrich_property.
        db.session.commit()
        service = NeighboursService()
        previous_by_id = {row["id"]: row["previous"] for row in plan["rows"]}
        # No resume claim: after a partial run the plan intentionally fails its
        # baseline comparison and must be regenerated by an explicit dry-run.
        with (
            inflight("backfill_neighbours", resumable=False)
            if properties
            else nullcontext()
        ):
            for prop in properties:
                try:
                    result = service.enrich(
                        prop, commit=True, expected_previous=previous_by_id[prop.id]
                    )
                    logger.info("property=%s status=%s", prop.id, result.get("status"))
                except Exception:
                    db.session.rollback()
                    raise


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    main()
